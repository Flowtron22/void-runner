import assert from 'node:assert/strict';
import {loadBattleArt,clearBattleArt} from '../js/ui/BattleArt.js';
const image={style:{},complete:true,naturalWidth:640,removeAttribute(name){delete this[name];}};
loadBattleArt(image,'first.gif');
assert.equal(image.style.visibility,'hidden','previous decoded pixels stay hidden during loading');
const firstLoad=image.onload,firstError=image.onerror;
firstLoad();assert.equal(image.style.visibility,'visible');
loadBattleArt(image,'second.gif');
assert.equal(image.style.visibility,'hidden');
image.complete=false;image.onload();assert.equal(image.style.visibility,'hidden','a queued event cannot reveal an incomplete replacement');
image.complete=true;
firstLoad();firstError();assert.equal(image.style.visibility,'hidden','old request callbacks cannot reveal or replace the next fight');
image.onload();assert.equal(image.style.visibility,'visible');
firstError();assert.equal(image.style.visibility,'visible','late old errors cannot hide current artwork');
const secondLoad=image.onload;
clearBattleArt(image);
assert.equal(image.src,undefined);assert.equal(image.onload,null);assert.equal(image.style.visibility,'hidden');
secondLoad();assert.equal(image.style.visibility,'hidden','leaving combat invalidates pending loads');
loadBattleArt(image,'cached.gif');image.onload();assert.equal(image.style.visibility,'visible');
loadBattleArt(image,'broken.gif');image.onerror();assert.equal(image.style.visibility,'hidden');
console.log('Battle art: previous GIF hidden, current load revealed, stale callbacks ignored, exit cleanup and errors passed.');
